from datetime import datetime, timedelta
from typing import Dict, Any, List

def generate_ics_calendar(trip: Dict[str, Any], route_name: str, origin_stop: str, dest_stop: str) -> str:
    """
    Generates a valid RFC 5545 iCalendar string for a campus bus trip.
    """
    now_str = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    
    # Base on today with trip start time
    start_parts = [int(p) for p in trip.get("start_time", "08:00:00").split(":")]
    dt_today = datetime.now().replace(hour=start_parts[0], minute=start_parts[1], second=0, microsecond=0)
    dt_end = dt_today + timedelta(minutes=25)

    dtstart = dt_today.strftime("%Y%m%dT%H%M%S")
    dtend = dt_end.strftime("%Y%m%dT%H%M%S")
    uid = f"routepulse-{trip.get('trip_id', 'trip')}-{int(dt_today.timestamp())}@routepulse.local"

    ics_content = f"""BEGIN:VCALENDAR
VERSION:2.0
PRODID:-//RoutePulse//Campus Transport Planning//EN
CALSCALE:GREGORIAN
METHOD:PUBLISH
BEGIN:VEVENT
UID:{uid}
DTSTAMP:{now_str}
DTSTART:{dtstart}
DTEND:{dtend}
SUMMARY:Campus Transit: {route_name}
DESCRIPTION:Trip {trip.get('trip_id')} from {origin_stop} to {dest_stop}. Vehicle: {trip.get('vehicle_id', 'Bus')}. Plan generated by RoutePulse.
LOCATION:{origin_stop}
STATUS:CONFIRMED
END:VEVENT
END:VCALENDAR"""
    return ics_content

def generate_operator_report_markdown(
    baseline_metrics: Dict[str, Any],
    proposed_metrics: Dict[str, Any],
    deltas: Dict[str, Any],
    recommendations: List[Dict[str, Any]],
    ml_travel_metrics: Dict[str, Any],
    ml_demand_metrics: Dict[str, Any]
) -> str:
    """
    Generates detailed Operator Report in Markdown format.
    """
    md = f"""# RoutePulse - Campus Transport Operational Assessment & Optimization Report
**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}  
**Campus System:** Stanford-Style Unified Academic & Residential Shuttle Network  

---

## 1. Executive Summary & Measurable Outcomes
The RoutePulse engine executed prescriptive schedule and fleet optimization over the baseline campus transport timetable.
All operations satisfy hard fleet and layover constraints.

| Operational Metric | Baseline Timetable | RoutePulse Proposed Plan | Delta Improvement |
| :--- | :--- | :--- | :--- |
| **Overcrowded Trips (>85% cap)** | {baseline_metrics.get('overcrowded_trips')} trips | {proposed_metrics.get('overcrowded_trips')} trips | **{deltas.get('overcrowded_trips')} trips** |
| **Capacity Violations (>100% cap)** | {baseline_metrics.get('capacity_violations')} trips | {proposed_metrics.get('capacity_violations')} trips | **{deltas.get('capacity_violations')} trips** |
| **Missed Connections** | {baseline_metrics.get('missed_connections')} incidents | {proposed_metrics.get('missed_connections')} incidents | **{deltas.get('missed_connections')} incidents** |
| **Average Passenger Wait** | {baseline_metrics.get('average_wait_min')} min | {proposed_metrics.get('average_wait_min')} min | **{deltas.get('average_wait_min')} min** |
| **Unmet Demand** | {baseline_metrics.get('unmet_demand_pax')} pax | {proposed_metrics.get('unmet_demand_pax')} pax | **{deltas.get('unmet_demand_pax')} pax** |
| **Fleet Total Travel** | {baseline_metrics.get('total_vehicle_km')} km | {proposed_metrics.get('total_vehicle_km')} km | **+{deltas.get('total_vehicle_km')} km** |

---

## 2. Machine Learning Validation Evidence (Predict-then-Optimize)

### A. Segment Travel-Time Quantile Regressor (P10 / P50 / P90)
- **Model:** Scikit-Learn `HistGradientBoostingRegressor` with Conformal Calibration.
- **Evaluation Split:** Strict chronological split (earliest 75% train, latest 25% test; zero data leakage).
- **Model MAE:** `{ml_travel_metrics.get('model_mae_sec', 0)}s` vs **Static Timetable Baseline:** `{ml_travel_metrics.get('baseline_mae_sec', 0)}s` (**{ml_travel_metrics.get('improvement_pct', 0)}% improvement**).
- **Calibrated Prediction Window Coverage:** `{ml_travel_metrics.get('calibrated_window_coverage_pct', 0)}%` (target $\ge 80\%$).
- **Conformal Margin:** `+{ml_travel_metrics.get('conformal_margin_sec', 0)}s`.

### B. Stop Demand Model
- **Model:** Gradient Boosting with 15-minute time-bucket aggregation.
- **Model MAE:** `{ml_demand_metrics.get('model_mae_passengers', 0)}` passengers vs **Same-Time-Last-Week Baseline:** `{ml_demand_metrics.get('baseline_mae_passengers', 0)}` passengers (**{ml_demand_metrics.get('improvement_pct', 0)}% improvement**).

---

## 3. Recommended Schedule Interventions & Trade-Offs

"""
    for idx, rec in enumerate(recommendations, 1):
        md += f"### {idx}. {rec.get('title')}\n"
        md += f"- **Target Route:** `{rec.get('route_id')}`\n"
        md += f"- **Operational Rationale:** {rec.get('reason')}\n"
        md += f"- **Quantified Trade-Off:** {rec.get('quantified_tradeoff')}\n\n"

    md += r"""
---
## 4. Hard Constraint Certification
The solver guarantees:
1. **Fleet Capacity Limit:** No vehicle assigned exceeds available campus units.
2. **Double Booking:** Zero instances of vehicle overlap.
3. **Minimum Layover:** Minimum 5-minute depot/terminal buffer strictly maintained.
4. **Schedule Integrity:** Immutable evaluation window preserves reproducible benchmarking.
"""
    return md
